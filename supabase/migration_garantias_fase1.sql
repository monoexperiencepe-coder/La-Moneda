-- Lectura: admin / socio / contador activos (mismo tenant vía empresa_id en app)
drop policy if exists "guarantee_settings_select" on public.guarantee_settings;
create policy "guarantee_settings_select"
  on public.guarantee_settings for select to authenticated
  using (
    exists (
      select 1 from public.user_profiles p
      where p.id = auth.uid()
        and coalesce(p.is_active, true)
        and p.role in ('admin', 'socio', 'contador')
        and (p.empresa_id is null or p.empresa_id = guarantee_settings.empresa_id)
    )
  );

